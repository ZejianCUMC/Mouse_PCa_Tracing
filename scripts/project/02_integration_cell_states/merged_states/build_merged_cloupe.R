suppressPackageStartupMessages({library(Seurat);library(Matrix);library(loupeR);library(jsonlite)})
d<-normalizePath(commandArgs(TRUE)[1]);stopifnot(file.exists(file.path(d,'PROJECTIONS_COMPLETE.json')))
manifest<-fromJSON(file.path(d,'COUNTS_COMPLETE.json'));stopifnot(manifest$status=='PASS')
mat<-Read10X_h5(file.path(d,'all_counts_PRIVATE.h5'),use.names=TRUE,unique.features=FALSE)
features<-read.csv(file.path(d,'features.csv'),check.names=FALSE)
meta<-read.csv(file.path(d,'metadata_PRIVATE.csv'),row.names=1,check.names=FALSE)
stopifnot(nrow(mat)==manifest$features,ncol(mat)==manifest$cells,identical(rownames(mat),features$symbol),identical(colnames(mat),rownames(meta)),all(Matrix::colSums(mat)==meta$total_counts))
ids<-paste0('c',seq_len(length(unique(meta$final_cluster))));states<-vapply(ids,function(k)unique(meta$putative_state[meta$final_cluster==k]),character(1))
clusters<-list(Putative_cell_state=factor(meta$putative_state,levels=states),Cluster_ID=factor(meta$final_cluster,levels=ids),Model=factor(meta$model),Treatment=factor(meta$treatment,levels=c('Intact','Castration','Castration+ENZA')),Run_ID=factor(meta$run_id),Sample_ID=factor(meta$sample_id))
projections<-list()
for(nm in c('UMAP','tSNE','Diffmap')){
 fname<-switch(nm,UMAP='umap_PRIVATE.csv',tSNE='tsne_PRIVATE.csv',Diffmap='diffmap_PRIVATE.csv')
 df<-read.csv(file.path(d,fname),row.names=1,check.names=FALSE)
 stopifnot(identical(rownames(df),colnames(mat)),ncol(df)==2,all(is.finite(as.matrix(df))))
 projections[[nm]]<-as.matrix(df)
}
stopifnot(validate_count_mat(mat,feature_ids=features$gene_id)$success,validate_clusters(clusters,ncol(mat))$success,validate_projections(projections,ncol(mat))$success)
h5<-file.path(d,'louper_input_PRIVATE.h5')
stopifnot(loupeR:::create_hdf5(mat,clusters,projections,h5,feature_ids=features$gene_id,seurat_obj_version=NULL)$success)
name<-'Npp_tumor_merged_final_states_all_genes';target<-file.path(d,paste0(name,'.cloupe'))
stopifnot(!file.exists(target))
cat('Creating all-gene Loupe file with three verified projections\n')
result<-loupeR:::louper_create_cloupe(h5,output_dir=d,output_name=name,force=FALSE)
stopifnot(result$success,file.exists(target),file.info(target)$size>1e6)
write_json(list(status='PASS',cells=ncol(mat),features=nrow(mat),states=length(ids),projections=names(projections),categories=names(clusters),loupeR_version=as.character(packageVersion('loupeR')),bytes=file.info(target)$size),file.path(d,'CLOUPE_COMPLETE.json'),auto_unbox=TRUE,pretty=TRUE)
cat('PASS: native Louper build complete\n')
